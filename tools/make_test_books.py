def make_epub(path: Path):
    from ebooklib import epub

    book = epub.EpubBook()
    book.set_identifier("test-book-001")
    book.set_title("增长的第一性原理（测试书）")
    book.set_language("zh-CN")
    book.add_author("测试作者")

    chapters = []
    for i, (title, body) in enumerate(CHAPTERS, 1):
        html_body = "".join(f"<p>{ln.strip()}</p>" for ln in body.strip().split("\n") if ln.strip())
        c = epub.EpubHtml(title=title, file_name=f"ch{i}.xhtml", lang="zh-CN")
        c.content = f"<h1>第{i}章 {title}</h1>{html_body}"
        book.add_item(c)
        chapters.append(c)

    book.toc = chapters
    book.add_item(epub.EpubNcx())
    book.add_item(epub.EpubNav())
    book.spine = ["nav"] + chapters
    epub.write_epub(str(path), book)
    print(f"[ok] EPUB 测试书: {path}")


def make_pdf(path: Path):
    import pymupdf

    doc = pymupdf.open()
    for i, (title, body) in enumerate(CHAPTERS, 1):
        page = doc.new_page()
        text = f"第{i}章 {title}\n\n{body.strip()}"
        page.insert_textbox(
            pymupdf.Rect(50, 50, 545, 780), text,
            fontname="china-s", fontsize=11,
        )
    doc.set_metadata({"title": "增长的第一性原理（测试书）", "author": "测试作者"})
    doc.save(str(path))
    print(f"[ok] PDF 测试书: {path}")


